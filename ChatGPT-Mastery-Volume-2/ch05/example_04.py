"""
Production Twilio Media Streams to OpenAI Realtime WebSocket Bridge
Author: Vatsal Shah, Enterprise AI Architect
Bridges PSTN phone calls to native multimodal GPT-4o voice over G.711 μ-law.
"""
import os
import json
import base64
import asyncio
import websockets
from fastapi import FastAPI, WebSocket
from fastapi.responses import HTMLResponse

app = FastAPI()

OPENAI_API_KEY = os.getenv("OPENAI_API_KEY")
VOICE_MODEL = "gpt-4o-realtime-preview"

@app.websocket("/media-stream")
async def handle_media_stream(twilio_ws: WebSocket):
    await twilio_ws.accept()
    print("📞 Twilio Media Stream Connected.")

    stream_sid = None
    openai_url = f"wss://api.openai.com/v1/realtime?model={VOICE_MODEL}"
    headers = {
        "Authorization": f"Bearer {OPENAI_API_KEY}",
        "OpenAI-Beta": "realtime=v1"
    }

    async with websockets.connect(openai_url, extra_headers=headers) as openai_ws:
        # Step 1: Configure Realtime Session for Telephony (G.711 μ-law @ 8kHz)
        init_session = {
            "type": "session.update",
            "session": {
                "input_audio_format": "g711_ulaw",
                "output_audio_format": "g711_ulaw",
                "voice": "alloy",
                "instructions": "You are a professional enterprise customer service representative. Be concise and helpful.",
                "turn_detection": {
                    "type": "server_vad",
                    "threshold": 0.5,
                    "silence_duration_ms": 500
                }
            }
        }
        await openai_ws.send(json.dumps(init_session))
        print("✅ OpenAI Realtime session initialized for G.711 μ-law.")

        # Step 2: Forward Twilio Audio to OpenAI
        async def twilio_to_openai():
            nonlocal stream_sid
            try:
                while True:
                    message_text = await twilio_ws.receive_text()
                    data = json.loads(message_text)
                    event_type = data.get("event")

                    if event_type == "start":
                        stream_sid = data["start"]["streamSid"]
                        print(f"🎬 Call Stream SID: {stream_sid}")

                    elif event_type == "media":
                        # Raw G.711 μ-law base64 audio from caller
                        payload = data["media"]["payload"]
                        audio_event = {
                            "type": "input_audio_buffer.append",
                            "audio": payload
                        }
                        await openai_ws.send(json.dumps(audio_event))

                    elif event_type == "stop":
                        print("Call finished by user.")
                        break
            except Exception as e:
                print(f"Twilio Ingestion Error: {e}")

        # Step 3: Forward OpenAI Audio back to Twilio
        async def openai_to_twilio():
            try:
                async for raw_msg in openai_ws:
                    event = json.loads(raw_msg)
                    event_type = event.get("type")

                    # Handle audio deltas generated by model
                    if event_type == "response.audio.delta":
                        audio_payload = event.get("delta")
                        if stream_sid and audio_payload:
                            twilio_media_event = {
                                "event": "media",
                                "streamSid": stream_sid,
                                "media": {"payload": audio_payload}
                            }
                            await twilio_ws.send_text(json.dumps(twilio_media_event))

                    # Handle barge-in interruption: Clear Twilio audio buffer
                    elif event_type == "input_audio_buffer.speech_started":
                        print("⚡ Interruption detected! Clearing Twilio playback buffer.")
                        if stream_sid:
                            await twilio_ws.send_text(json.dumps({
                                "event": "clear",
                                "streamSid": stream_sid
                            }))

            except Exception as e:
                print(f"OpenAI Egress Error: {e}")

        # Run full-duplex bridge concurrently
        await asyncio.gather(twilio_to_openai(), openai_to_twilio())
